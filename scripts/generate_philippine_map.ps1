$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$uri = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson'
$data = Invoke-RestMethod -Uri $uri -TimeoutSec 60
$country = $data.features | Where-Object { $_.properties.ADM0_A3 -eq 'PHL' } | Select-Object -First 1
if (!$country) { throw 'Philippine map geometry was not found.' }
$invariant = [Globalization.CultureInfo]::InvariantCulture
$lines = New-Object 'System.Collections.Generic.List[string]'
$lines.Add("import 'dart:ui';")
$lines.Add('')
$lines.Add('// Generated by scripts/generate_philippine_map.ps1. Longitude/latitude coordinates.')
$lines.Add('// Made with Natural Earth (public domain), 1:50m country coastline geometry.')
$lines.Add('// Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson')
$lines.Add('// License: https://www.naturalearthdata.com/about/terms-of-use/')
$lines.Add('const philippineCoastlines = <List<Offset>>[')
foreach ($polygon in $country.geometry.coordinates) {
    $ring = $polygon[0]
    $lines.Add('  [')
    foreach ($point in $ring) {
        $longitude = ([double]$point[0]).ToString('F4', $invariant)
        $latitude = ([double]$point[1]).ToString('F4', $invariant)
        $lines.Add("    Offset($longitude, $latitude),")
    }
    $lines.Add('  ],')
}
$lines.Add('];')
$destination = Join-Path $projectRoot 'lib/features/home/widgets/philippine_coastlines.dart'
[IO.File]::WriteAllLines($destination, $lines, (New-Object Text.UTF8Encoding($false)))
Write-Output "Generated Philippine coastlines: $($country.geometry.coordinates.Count) islands."
